#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md: the fonts, JavaScript packages and Rust
 * crates that Markpion ships, with their licenses and license texts.
 *
 *   npm run notices            (regenerate)
 *   npm run notices -- --check (fail if the file is out of date; CI runs this)
 *
 * JavaScript: the production dependency tree (`npm ls --omit=dev`). Rust: the
 * crates the app links on any of its platforms (normal dependencies only, not
 * build scripts or tests), from `cargo metadata`. Fonts: their own copyright
 * and license strings, read from the font files.
 */
import { execSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const OUT = "THIRD_PARTY_NOTICES.md";
// Fixed commands (no user input), run through the shell so npm resolves on Windows too.
const run = (cmd, args) => execSync([cmd, ...args].join(" "), { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

/** The license files in a package folder (LICENSE, LICENSE-MIT, COPYING…), as text. */
function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)([-._].*)?$/i.test(f) && !/\.(js|ts|json|html)$/i.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim())
    .filter(Boolean);
}

function npmPackages() {
  const dirs = run("npm", ["ls", "--omit=dev", "--all", "--parseable"]).trim().split(/\r?\n/).slice(1);
  const seen = new Map();
  for (const dir of dirs) {
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const key = `${pkg.name}@${pkg.version}`;
    if (seen.has(key)) continue;
    const license = typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? pkg.licenses?.map((l) => l.type).join(" OR ") ?? "");
    seen.set(key, { name: pkg.name, version: pkg.version, license, texts: licenseTexts(dir) });
  }
  return [...seen.values()];
}

function rustCrates() {
  const meta = JSON.parse(run("cargo", ["metadata", "--format-version", "1", "--locked", "--manifest-path", "src-tauri/Cargo.toml"]));
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  // Follow normal dependencies (for any target) from the app crate.
  const keep = new Set();
  const queue = [meta.resolve.root];
  while (queue.length) {
    const id = queue.pop();
    if (keep.has(id)) continue;
    keep.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
    }
  }
  keep.delete(meta.resolve.root);
  return [...keep].map((id) => {
    const p = byId.get(id);
    const dir = p.manifest_path.replace(/[\\/]Cargo\.toml$/, "");
    return { name: p.name, version: p.version, license: p.license ?? "", texts: licenseTexts(dir) };
  });
}

function fonts() {
  const fontkit = require("fontkit");
  const ofl = readFileSync("scripts/licenses/OFL-1.1.txt", "utf8").replace(/\r\n/g, "\n").trim();
  const vfsMod = require("pdfmake/build/vfs_fonts.js");
  const vfs = vfsMod.default ?? vfsMod;
  const files = [
    { name: "Roboto", where: "PDF export (from pdfmake)", font: fontkit.create(Buffer.from(vfs["Roboto-Regular.ttf"], "base64")) },
    ...["KaTeX_Main-Regular", "KaTeX_AMS-Regular"].map((n) => ({ name: n, where: "symbols in PDF formulas (from katex)", font: fontkit.create(readFileSync(`node_modules/katex/dist/fonts/${n}.ttf`)) })),
  ];
  return files.map(({ name, where, font }) => ({ name, where, version: font.getName("version") ?? "", notice: [font.getName("copyright"), font.getName("license")].filter(Boolean).join("\n\n"), text: ofl }));
}

const cell = (s) => (s || "not stated").replace(/\|/g, "\\|");
const sortByName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true });

function render() {
  const npm = npmPackages().sort(sortByName);
  const rust = rustCrates().sort(sortByName);
  const fontList = fonts();
  const lines = [
    "# Third-party notices",
    "",
    "Markpion includes fonts and open-source software made by others. This file lists them with their licenses, and below, the license texts their packages include.",
    "",
    "Generated by `npm run notices` from the dependency lists (`package-lock.json`, `src-tauri/Cargo.lock`); don't edit it by hand.",
    "",
    "## Fonts",
    "",
    "| Font | Used for | Version | License |",
    "| --- | --- | --- | --- |",
    ...fontList.map((f) => `| ${f.name} | ${f.where} | ${cell(f.version)} | OFL-1.1 |`),
    "",
    ...fontList.flatMap((f) => [`### ${f.name}`, "", "```text", f.notice, "```", ""]),
    "### SIL Open Font License 1.1",
    "",
    "```text",
    fontList[0].text,
    "```",
    "",
    `## JavaScript packages (${npm.length})`,
    "",
    "| Package | Version | License |",
    "| --- | --- | --- |",
    ...npm.map((p) => `| ${cell(p.name)} | ${p.version} | ${cell(p.license)} |`),
    "",
    `## Rust crates (${rust.length})`,
    "",
    "| Crate | Version | License |",
    "| --- | --- | --- |",
    ...rust.map((p) => `| ${cell(p.name)} | ${p.version} | ${cell(p.license)} |`),
    "",
    "## License texts",
    "",
    "Each text below is listed once, with the packages that include it. A package without a license file is covered by the license named in the tables above.",
    "",
  ];
  // Group identical texts so a common license appears once.
  const groups = new Map();
  for (const p of [...npm, ...rust]) {
    for (const text of p.texts) {
      const key = text.replace(/\s+/g, " ");
      if (!groups.has(key)) groups.set(key, { text, users: [] });
      groups.get(key).users.push(`${p.name} ${p.version}`);
    }
  }
  [...groups.values()]
    .sort((a, b) => a.users[0].localeCompare(b.users[0]))
    .forEach((g, i) => lines.push(`### Text ${i + 1}`, "", `Used by: ${g.users.join(", ")}`, "", "```text", g.text.replace(/```/g, "'''"), "```", ""));
  return lines.join("\n");
}

const content = render();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== content) {
    console.error(`${OUT} is out of date. Run \`npm run notices\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, content);
  console.log(`Wrote ${OUT} (${Math.round(content.length / 1024)} KB).`);
}
